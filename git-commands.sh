# commit commands
git add .                           # Добавить индексацию
git commit -m "add bubdi babdi"     # Сделать коммит
git push                            # Сделать пуш (Отправить изменения в удалённый репозиторий)

git pull                            # Получить изменения из удалённого репозитория

# Branch commands
git branch -m old-branch new-branch # Создание ветки

git switch                          # Сменить ветку

